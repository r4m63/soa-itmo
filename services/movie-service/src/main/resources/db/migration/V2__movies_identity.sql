-- V1 used SERIAL. Keep the next unused ID when converting an existing database.
DO
$$
    DECLARE
        next_id BIGINT;
    BEGIN
        SELECT GREATEST(
                       COALESCE((SELECT MAX(id) FROM movies), 0) + 1,
                       (SELECT last_value + CASE WHEN is_called THEN 1 ELSE 0 END FROM movies_id_seq)
               )
        INTO next_id;

        ALTER TABLE movies
            ALTER COLUMN id DROP DEFAULT;
        DROP SEQUENCE movies_id_seq;
        ALTER TABLE movies
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        EXECUTE format('ALTER TABLE movies ALTER COLUMN id RESTART WITH %s', next_id);
    END
$$;
